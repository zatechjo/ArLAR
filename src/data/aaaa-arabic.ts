const titleByVideoId = new Map(
  archive.videos
    .filter((video) => video.type === "session")
    .map((video, index) => [video.id, sessionTitles[index]]),
);

export function arabicAaaaVideoTitle(video: AaaaVideo) {
  return titleByVideoId.get(video.id) ?? (video.type === "qa" ? "أسئلة وأجوبة" : video.title);
}

export function arabicAaaaEventHeading(event: AaaaEvent) {
  return eventHeadings[event.eventOrder - 1] ?? event.heading;
}

export function arabicAaaaEventDate(event: AaaaEvent) {
  return eventDates[event.eventOrder - 1] ?? event.dateDisplay;
}
